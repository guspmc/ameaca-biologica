'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { criarArquivosMestre, MAX_BYTES } = require('../servidor/arquivos-mestre');
const pasta = fs.mkdtempSync(path.join(os.tmpdir(), 'ab-arquivos-'));
const arquivos = criarArquivosMestre({ pasta });
const png = Buffer.from([0x89,0x50,0x4e,0x47,0x0d,0x0a,0x1a,0x0a,0,0,0,0]);
const salvo = arquivos.salvar('a1b2c3d4e5f6', 'imagem.png', 'image/png', png);
assert.equal(salvo.ok, true);
assert.equal(arquivos.ler('a1b2c3d4e5f6', salvo.arquivo).mime, 'image/png');
assert.deepEqual(arquivos.ler('a1b2c3d4e5f6', salvo.arquivo).dados, png);
assert.equal(arquivos.ler('abcdefabcdef', salvo.arquivo), null);
assert.equal(arquivos.ler('a1b2c3d4e5f6', '../' + salvo.arquivo), null);
assert.equal(arquivos.salvar('a1b2c3d4e5f6', 'perigoso.html', 'text/html', Buffer.from('x')).status, 415);
assert.equal(arquivos.salvar('a1b2c3d4e5f6', 'fake.png', 'image/jpeg', png).status, 415);
assert.equal(arquivos.salvar('a1b2c3d4e5f6', 'vazio.txt', 'text/plain', Buffer.alloc(0)).status, 400);
assert.equal(arquivos.salvar('a1b2c3d4e5f6', 'grande.txt', 'text/plain', Buffer.alloc(MAX_BYTES + 1)).status, 413);
arquivos.apagarMesa('a1b2c3d4e5f6');
assert.equal(arquivos.ler('a1b2c3d4e5f6', salvo.arquivo), null);
fs.rmSync(pasta, { recursive: true, force: true });
console.log('Arquivos do Mestre: tudo OK');
